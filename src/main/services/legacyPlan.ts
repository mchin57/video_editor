/** One converted project, for the summary the batch shows. */
export interface ConversionReport {
  from: string
  /** The new `.reel` (null when the conversion failed). */
  to: string | null
  /** Library items whose original was located (footage or generated). */
  found: number
  /** Generated originals copied into `generated/`. */
  copied: number
  /** File names of originals that could not be located, plus a count of
   *  clips the old library had no record for. */
  missing: string[]
  error?: string
}

/** The `missing` entry for ids the old library had no record of. */
export const noRecordLine = (n: number): string => `${n} clip${n === 1 ? '' : 's'} with no record in the old library`

/** One line per project for the batch summary. */
export function reportLine(r: ConversionReport): string {
  const name = basename(r.from, extname(r.from)) || r.from
  if (r.error) return `✗ ${name}: ${r.error}`
  const counts = `${r.found} file${r.found === 1 ? '' : 's'} found${r.copied ? ` (${r.copied} copied)` : ''}`
  return r.missing.length ? `! ${name}: ${counts}, missing ${r.missing.join(', ')}` : `✓ ${name}: ${counts}`
}

export const isReelFile = (name: string): boolean => name.toLowerCase().endsWith(`.${REEL_EXT}`)
