/**
 * Converting a legacy project (schema < 24: a lone `.reel` whose media lives in
 * the old global store `<data>/media/<hash>/`) into a project folder — the
 * pure decisions. `legacyConvert.ts` does the I/O. @see docs/PROJECT-FOLDERS.md
 * "Migration".
 */

import { basename, dirname, extname, join, parse, relative, isAbsolute } from 'node:path'
import { PROJECT_VERSION } from '@shared/project'
import { REEL_EXT, isMediaId } from './projectLayout'

/** A document whose media still lives in the old global store. */
export function isLegacyDoc(raw: unknown): boolean {
  const v = (raw as { version?: unknown } | null)?.version
  return typeof v !== 'number' || v < PROJECT_VERSION
}

/** Facts about the place a legacy `.reel` sits, gathered by the caller. */
export interface PlaceFacts {
  /** How many `.reel` files share its directory (itself included). */
  reelsInDir: number
  /** Its directory is the folder a batch conversion was pointed at (where
   *  loose project files sit side by side) or a user folder like Documents —
   *  never adopt that as one project's folder. */
  dirIsShared: boolean
  /** Whether a candidate folder is already taken by another project. */
  taken: (folder: string) => boolean
}

/**
 * The project folder a legacy `.reel` converts into. A file alone in its own
 * folder (the owner's habit: footage + project together) converts IN PLACE —
 * that folder becomes the project. A loose file gets a new `<Name>/` beside
 * it, suffixed if a project already has that name.
 */
export function conversionFolder(reelPath: string, facts: PlaceFacts): { root: string; inPlace: boolean } {
  const dir = dirname(reelPath)
  if (facts.reelsInDir === 1 && !facts.dirIsShared) return { root: dir, inPlace: true }
  const name = parse(reelPath).name
  let root = join(dir, name)
  for (let n = 2; facts.taken(root); n++) root = join(dir, `${name} (${n})`)
  return { root, inPlace: false }
}

/** Where the legacy file is kept as a backup once converted (`x.reel` →
 *  `x.reel-legacy`): out of the Open dialog's `.reel` filter, still readable. */
export const legacyBackupPath = (reelPath: string): string => `${reelPath}-legacy`

/** Store ids a legacy document uses — any id mentioned anywhere in its text
 *  (the same deliberately generous rule as the project sweep). */
export function legacyIdsIn(docText: string, storeIds: string[]): string[] {
  return storeIds.filter((id) => isMediaId(id) && docText.includes(`"${id}"`))
}

/** A legacy original under the app's data dir was GENERATED by the app (nobg,
 *  audiofx, extracted, stills); anything else is the user's footage. */
export function isGeneratedPath(originalPath: string, dataDir: string): boolean {
  const rel = relative(dataDir.toLowerCase(), originalPath.toLowerCase())
  return !!rel && !rel.startsWith('..') && !isAbsolute(rel)
}

/** How one legacy asset is adopted. */
export type AdoptAction =
  | { kind: 'adopt'; from: string; generated: boolean }
  | { kind: 'missing'; reason: 'gone' | 'different' }

/** Adopt the original only if it is still there AND still the same bytes. */
export function adoptAction(
  originalPath: string,
  facts: { exists: boolean; hash: string | null },
  id: string,
  dataDir: string
): AdoptAction {
  if (!facts.exists) return { kind: 'missing', reason: 'gone' }
  if (facts.hash !== id) return { kind: 'missing', reason: 'different' }
  return { kind: 'adopt', from: originalPath, generated: isGeneratedPath(originalPath, dataDir) }
}

/** Derived files worth carrying over from the old store (linked, never copied —
 *  the cache rebuilds anything that doesn't come along). */
export const LEGACY_CACHE_FILES = ['proxy.mp4', 'proxy.webm', 'audio.m4a', 'image.png', 'waveform.png', 'thumb.jpg'] as const

/** The old global store's directories (all of it goes once everything is converted). */
export const LEGACY_STORE_DIRS = ['media', 'nobg', 'audiofx', 'extracted', 'stills'] as const

/** One converted project, for the summary the batch shows. */
export interface ConversionReport {
  from: string
  /** The new `.reel` (null = the working copy, converted into the scratch project). */
  to: string | null
  linked: number
  copied: number
  /** File names of originals that could not be adopted. */
  missing: string[]
  error?: string
}

/** One line per project for the batch summary. */
export function reportLine(r: ConversionReport): string {
  const name = basename(r.from, extname(r.from)) || r.from
  if (r.error) return `✗ ${name}: ${r.error}`
  const counts = `${r.linked + r.copied} file${r.linked + r.copied === 1 ? '' : 's'}${r.copied ? ` (${r.copied} copied)` : ''}`
  return r.missing.length ? `! ${name}: ${counts}, missing ${r.missing.join(', ')}` : `✓ ${name}: ${counts}`
}

export const isReelFile = (name: string): boolean => name.toLowerCase().endsWith(`.${REEL_EXT}`)
